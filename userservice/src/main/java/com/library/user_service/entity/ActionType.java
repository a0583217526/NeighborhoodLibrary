package com.library.user_service.entity;

public enum ActionType {

    USER_REGISTER,            // רישום משתמש חדש במערכת
    USER_LOGIN,               // התחברות למערכת (רגילה או גוגל)
    USER_UPDATE_PROFILE,      // עדכון פרטי האזור האישי (טלפון, שכונה וכו')
    USER_DEACTIVATE,          // הקפאת / השבתת החשבון

    // --- אירועים שיגיעו משירות הספרים (ניהול קטלוג) ---
    BOOK_ADDED,               // המשתמש הוסיף ספר חדש לקטלוג (לפי האפיון: תומך, קטגוריה, תיאור קצר, מצב הספר)
    BOOK_UPDATED,             // בעל הספר עדכן פרטי ספר
    BOOK_REMOVED,             // בעל הספר מחק ספר מהמערכת

    // --- אירועים שיגיעו משירות ההשאלות (ניהול ההשאלות והבקשות) ---
    LOAN_REQUEST_CREATED,     // משתמש שלח בקשת השאלה חדשה לספר
    LOAN_REQUEST_APPROVED,    // בעל הספר אישר את בקשת ההשאלה (סטטוס: הושאל)
    LOAN_REQUEST_REJECTED,    // בעל הספר דחה את בקשת ההשאלה
    LOAN_BOOK_RETURNED,       // הספר הוחזר בהצלחה וההשאלה הסתיימה
    LOAN_OVERDUE              // התראה / ציון במערכת שהספר באיחור (לפי סעיף "אילוצים מיוחדים")
}